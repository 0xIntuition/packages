function escapeRegExp(value: string): string {
	return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function kebabCase(value: string): string {
	return value
		.replace(/([a-z0-9])([A-Z])/g, '$1-$2')
		.replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
		.toLowerCase();
}

function getAbi(abiName: string): Abi {
	const abi = (protocol as Record<string, unknown>)[abiName];
	if (!Array.isArray(abi)) {
		throw new Error(`Could not find ABI export "${abiName}" in @0xintuition/protocol.`);
	}
	return abi as Abi;
}

function getAbiFunction(abiName: string, functionName: string): AbiFunction {
	const abi = getAbi(abiName);
	const match = abi.find(
		(item): item is AbiFunction => item.type === 'function' && item.name === functionName
	);
	if (!match) {
		throw new Error(`Function "${functionName}" not found in ABI "${abiName}".`);
	}
	return match;
}

// Wrappers that bubble MultiVault's custom errors import `{ type MultiVaultAbi, MultiVaultWithRevertsAbi }`;
// the encoder is generated against the plain contract ABI, so the revert-augmented variants are skipped.
const REVERT_AUGMENTED_ABI = /(?:WithReverts|BubbledErrors)Abi$/;

function extractAbiName(source: string, filePath: string): string {
	const match = source.match(/import\s*\{([^}]*)\}\s*from\s*['"]..\/..\/contracts['"]/);
	const abiNames = (match?.[1] ?? '')
		.split(',')
		.map((name) => name.replace(/^\s*type\s+/, '').trim())
		.filter((name) => /^[A-Za-z0-9_]+Abi$/.test(name) && !REVERT_AUGMENTED_ABI.test(name));
	if (abiNames.length !== 1 || !abiNames[0]) {
		throw new Error(`Could not find contract ABI import in ${filePath}.`);
	}
	return abiNames[0];
}

function extractDefinitionsFromSource(
	source: string,
	filePath: string,
	abiName: string,
	contract: CoreEncoderContract
): EncoderDefinition[] {
	const functionStarts = [...source.matchAll(/export\s+async\s+function\s+([A-Za-z0-9_]+)\s*\(/g)];
	const definitions: EncoderDefinition[] = [];

	for (let index = 0; index < functionStarts.length; index += 1) {
		const current = functionStarts[index];
		const next = functionStarts[index + 1];
		if (!current || current.index === undefined || !current[1]) {
			continue;
		}

		const segmentEnd = next?.index ?? source.length;
		const segment = source.slice(current.index, segmentEnd);
		if (!segment.includes('readContract(') && !segment.includes('simulateContract(')) {
			continue;
		}

		const wrapperName = current[1];
		const functionNameMatches = [...segment.matchAll(/functionName:\s*'([^']+)'/g)]
			.map((match) => match[1])
			.filter((name): name is string => Boolean(name));
		const uniqueFunctionNames = [...new Set(functionNameMatches)];

		// Skip composite wrappers (for example multicall aggregators).
		if (uniqueFunctionNames.length !== 1) {
			continue;
		}

		const [functionName] = uniqueFunctionNames;
		if (!functionName) {
			continue;
		}
		const typedMutabilityMatch = source.match(
			new RegExp(
				`ContractFunctionArgs<typeof\\s+${escapeRegExp(abiName)}\\s*,\\s*'([^']+)'\\s*,\\s*'${escapeRegExp(functionName)}'>`
			)
		);
		const abiFunction = getAbiFunction(abiName, functionName);
		const stateMutability = (typedMutabilityMatch?.[1] ??
			abiFunction.stateMutability) as SupportedMutability;
		const kind: CoreEncoderKind =
			stateMutability === 'view' || stateMutability === 'pure' ? 'read' : 'write';
		const encoderName = `${wrapperName}Encode`;

		definitions.push({
			contract,
			kind,
			encoderName,
			abiName,
			functionName,
			stateMutability,
			sourceWrapper: wrapperName,
			sourceFile: path.basename(filePath),
		});
	}

	return definitions;
}

async function getModuleDefinitions(moduleConfig: ModuleConfig): Promise<EncoderDefinition[]> {
	const fileNames = await fs.readdir(moduleConfig.sourceDir);
	const tsFiles = fileNames
		.filter((fileName) => fileName.endsWith('.ts'))
		.filter((fileName) => !fileName.endsWith('.unit.test.ts'))
		.filter((fileName) => fileName !== 'index.ts');

	const definitions: EncoderDefinition[] = [];

	for (const fileName of tsFiles) {
		const filePath = path.join(moduleConfig.sourceDir, fileName);
		const source = await fs.readFile(filePath, 'utf8');
		if (!source.includes('readContract(') && !source.includes('simulateContract(')) {
			continue;
		}

		const abiName = extractAbiName(source, filePath);
		const fileDefinitions = extractDefinitionsFromSource(
			source,
			filePath,
			abiName,
			moduleConfig.key
		);
		definitions.push(...fileDefinitions);
	}

	return definitions.sort((left, right) => left.encoderName.localeCompare(right.encoderName));
}

function renderEncoderFile(definition: EncoderDefinition): string {
	return `${GENERATED_HEADER}

	import { ${definition.abiName} } from '../../../../abis/core/index';
	import { type ContractFunctionArgs, encodeFunctionData, type Hex } from 'viem';

export function ${definition.encoderName}(
\t...args: ContractFunctionArgs<
\t\ttypeof ${definition.abiName},
\t\t'${definition.stateMutability}',
\t\t'${definition.functionName}'
\t>
): Hex {
\treturn encodeFunctionData({
\t\tabi: ${definition.abiName},
\t\tfunctionName: '${definition.functionName}',
\t\targs,
\t});
}
`;
}

function renderModuleManifest(
	moduleConfig: ModuleConfig,
	definitions: EncoderDefinition[]
): string {
	const rows = definitions
		.map(
			(definition) => `\t{
\t\tcontract: '${definition.contract}',
\t\tkind: '${definition.kind}',
\t\tencoderName: '${definition.encoderName}',
\t\tabiName: '${definition.abiName}',
\t\tfunctionName: '${definition.functionName}',
\t\tstateMutability: '${definition.stateMutability}',
\t\tsourceWrapper: '${definition.sourceWrapper}',
\t\tsourceFile: '${definition.sourceFile}',
\t},`
		)
		.join('\n');

	return `${GENERATED_HEADER}

import type { CoreEncoderManifestEntry } from '../types';

export const ${moduleConfig.manifestConst}: readonly CoreEncoderManifestEntry[] = [
${rows}
] as const;
`;
}

function renderModuleIndex(): string {
	return `${GENERATED_HEADER}

export * from './manifest';
export * from './read';
export * from './write';
`;
}

function renderKindIndex(definitions: EncoderDefinition[]): string {
	const exportLines = definitions
		.map((definition) => `export * from './${kebabCase(definition.encoderName)}';`)
		.join('\n');

	return `${GENERATED_HEADER}

${exportLines}
`;
}

async function clearDirectory(directoryPath: string): Promise<void> {
	await fs.rm(directoryPath, { recursive: true, force: true });
	await fs.mkdir(directoryPath, { recursive: true });
}

async function generateModule(moduleConfig: ModuleConfig): Promise<number> {
	const definitions = await getModuleDefinitions(moduleConfig);
	await clearDirectory(moduleConfig.outputDir);
	const readDir = path.join(moduleConfig.outputDir, 'read');
	const writeDir = path.join(moduleConfig.outputDir, 'write');
	await fs.mkdir(readDir, { recursive: true });
	await fs.mkdir(writeDir, { recursive: true });

	for (const definition of definitions) {
		const targetDir = definition.kind === 'read' ? readDir : writeDir;
		const filePath = path.join(targetDir, `${kebabCase(definition.encoderName)}.ts`);
		await fs.writeFile(filePath, renderEncoderFile(definition));
	}

	const readDefinitions = definitions.filter((definition) => definition.kind === 'read');
	const writeDefinitions = definitions.filter((definition) => definition.kind === 'write');

	await fs.writeFile(
		path.join(moduleConfig.outputDir, 'manifest.ts'),
		renderModuleManifest(moduleConfig, definitions)
	);
	await fs.writeFile(path.join(readDir, 'index.ts'), renderKindIndex(readDefinitions));
	await fs.writeFile(path.join(writeDir, 'index.ts'), renderKindIndex(writeDefinitions));
	await fs.writeFile(path.join(moduleConfig.outputDir, 'index.ts'), renderModuleIndex());

	return definitions.length;
}

async function main(): Promise<void> {
	let totalCount = 0;

	for (const moduleConfig of MODULES) {
		const count = await generateModule(moduleConfig);
		totalCount += count;
		console.log(`[generate-core-encoders] ${moduleConfig.key}: ${count}`);
	}

	console.log(`[generate-core-encoders] total: ${totalCount}`);
}

await main();
